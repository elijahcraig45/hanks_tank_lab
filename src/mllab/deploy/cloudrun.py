MAX_INSTANCES_CAP = 5
# A serving image only needs what unpickles and runs THIS model. The registered lock is the whole training environment (aiplatform,
# pybaseball, ...): a 3.1 GB image for a 742 KB model. The pickle is scanned (without running any of its code) for the libraries
# it references, and only those are installed, at the lock's exact pins. --full-lock installs everything.
MODEL_LIBS = {"xgboost": "xgboost", "lightgbm": "lightgbm", "catboost": "catboost"}
ALWAYS = {"numpy", "pandas", "scikit-learn", "scipy", "joblib", "threadpoolctl"}  # the app itself, and the sklearn API the wrappers need
# Cloud Run has no GPU. The standard xgboost wheel drags in ~470 MB of CUDA libraries; the CPU-only build has the same version and the
# same `import xgboost`, and predicts through the same CPU code. Parity against prod is re-verified after this swap.
CPU_VARIANTS = {"xgboost": "xgboost-cpu"}
MODULE_TO_PACKAGE = {**MODEL_LIBS, "sklearn": "scikit-learn", "numpy": "numpy", "pandas": "pandas", "scipy": "scipy", "joblib": "joblib"}
SERVICE_RE = re.compile(r"^[a-z]([a-z0-9-]{0,40}[a-z0-9])?$")

DOCKERFILE = """FROM python:3.12-slim
WORKDIR /app
COPY requirements.txt .
RUN pip install --no-cache-dir -r requirements.txt
COPY . .
ENV PYTHONPATH=/app/code PORT=8080
CMD exec uvicorn app:app --host 0.0.0.0 --port ${PORT}
"""

APP = '''"""Serving template generated by mllab. POST /predict {"rows": [{feature: value, ...}]} -> {"proba": [P(home win), ...]}"""
import json
import pickle
from pathlib import Path

import numpy as np
import pandas as pd
from fastapi import FastAPI, HTTPException

MAX_ROWS = 1000
HERE = Path(__file__).parent
with open(HERE / "model.pkl", "rb") as f:  # baked into the image from the hash-verified registry copy
    OBJ = pickle.load(f)

SCALER, FILL = None, {}
if isinstance(OBJ, dict) and "model" in OBJ and "features" in OBJ:  # the payload V10 and lab-trained models use
    MODEL, FEATURES = OBJ["model"], list(OBJ["features"])
    FILL, SCALER = OBJ.get("fill_values") or {}, OBJ.get("scaler")
elif isinstance(OBJ, dict):
    raise RuntimeError("unsupported model payload (keys: %s). Ensembles such as V8 need their own serving code." % sorted(OBJ)[:10])
elif hasattr(OBJ, "predict_proba"):  # a bare estimator: its own feature list, else the one registered with it
    MODEL = OBJ
    names = getattr(OBJ, "feature_names_in_", None)  # a numpy array: never use `or` on it
    FEATURES = list(names) if names is not None else json.loads((HERE / "features.json").read_text())
else:
    raise RuntimeError("unsupported model object: %s" % type(OBJ).__name__)
if not FEATURES:
    raise RuntimeError("no feature list: register the model with --features, or use a payload that carries its own")

app = FastAPI(title="mllab model", docs_url=None, redoc_url=None)


@app.get("/healthz")
def healthz():
    return {"ok": True, "features": len(FEATURES), "model": type(MODEL).__name__}


@app.post("/predict")
def predict(body: dict):
    rows = body.get("rows")
    if not isinstance(rows, list) or not rows or not all(isinstance(r, dict) for r in rows):
        raise HTTPException(400, "rows must be a non-empty list of objects")
    if len(rows) > MAX_ROWS:
        raise HTTPException(413, f"at most {MAX_ROWS} rows per request")
    df = pd.DataFrame(rows)
    missing = [c for c in FEATURES if c not in df.columns]
    if missing:
        raise HTTPException(422, f"missing features: {missing[:10]}{' ...' if len(missing) > 10 else ''}")
    try:
        X = df[FEATURES].astype(float)
    except (ValueError, TypeError) as e:
        raise HTTPException(422, f"features must be numeric or null: {str(e)[:120]}")
    X = X.fillna(pd.Series({k: v for k, v in FILL.items() if k in X.columns}, dtype=float)).fillna(0.0)  # same imputation as training
    Z = SCALER.transform(X) if SCALER is not None else X
    return {"proba": [float(p) for p in MODEL.predict_proba(Z)[:, 1]]}
'''


def _make_writable(root: Path) -> None:
    for p in [root, *root.rglob("*")]:
        if not p.is_symlink():
            p.chmod(p.stat().st_mode | 0o700)


class _Stub:
    """Stands in for every class/function a pickle references, so scanning records names and executes nothing of the pickle's."""

    def __init__(self, *a, **k):
        pass

    def __setstate__(self, state):
        pass

    def __call__(self, *a, **k):
        return _Stub()

    # pickles rebuild dicts, lists and sets through these; swallow them all (only the referenced NAMES matter here)
    def __setitem__(self, k, v):
        pass

    def append(self, v):
        pass

    def extend(self, v):
        pass

    def add(self, v):
        pass

    def update(self, *a, **k):
        pass


class _Recorder(pickle.Unpickler):
    def __init__(self, f, seen: set):
        super().__init__(f)
        self.seen = seen

    def find_class(self, module, name):
        self.seen.add(module.split(".")[0])
        return _Stub

    def persistent_load(self, pid):
        return None


def pickle_modules(path: str | Path) -> set[str]:
    """Top-level modules a pickle references. Never imports them and never runs the pickle's own callables."""
    seen: set = set()
    with open(path, "rb") as f:
        _Recorder(f, seen).load()
    return seen


def _pkg(line: str) -> str:
    return re.split(r"[=<>~!\[ ;@]", line.strip(), maxsplit=1)[0].lower().replace("_", "-")


def lean_requirements(lines: list[str], modules: set[str], local_modules: set[str] = frozenset()) -> list[str]:
    """The lock's exact pins for only what this model needs. Refuses (use full_lock) if the pickle needs something unpinned/unknown."""
    third_party = {m for m in modules if m not in sys.stdlib_module_names and m not in local_modules and m != "builtins"}
    unknown = sorted(m for m in third_party if m not in MODULE_TO_PACKAGE)
    if unknown:
        raise RegistryError(f"the model references {unknown}, which lean serving does not know how to install; use full_lock=True (--full-lock)")
    want = set(ALWAYS) | {MODULE_TO_PACKAGE[m] for m in third_party}
    if not any(MODULE_TO_PACKAGE[m] in MODEL_LIBS.values() or m == "sklearn" for m in third_party):
        raise RegistryError("could not tell which model library the pickle needs; use full_lock=True (--full-lock)")
    lock = {_pkg(l): l.strip() for l in lines if l.strip() and not l.strip().startswith("#")}
    missing = sorted(p for p in want & (set(MODEL_LIBS.values()) | {"scikit-learn"}) if p not in lock and p in {MODULE_TO_PACKAGE[m] for m in third_party})
    if missing:
        raise RegistryError(f"the model needs {missing} but the registered lock does not pin it; use full_lock=True or re-register with a complete lock")
    out = []
    for p in lock:
        if p in want:
            line = lock[p]
            if p in CPU_VARIANTS:  # same pin, CPU-only distribution
                line = CPU_VARIANTS[p] + line[len(p):] if line.lower().replace("_", "-").startswith(p) else line
            out.append(line)
    return out


def render_bundle(reg: Registry, project: str, model: str, version: str, out_dir: str | Path, *, full_lock: bool = False) -> Path:
    pkl = reg.verify(project, model, version)
    vdir = reg.version_dir(project, model, version)
    lock = vdir / "requirements.lock"
    if not lock.is_file():
        raise RegistryError(f"{project}/{model}/{version} has no requirements.lock; register with lockfile= to serve it")
    out = Path(out_dir)
    if out.exists():
        _make_writable(out)
        shutil.rmtree(out)
    out.mkdir(parents=True)
    shutil.copy2(pkl, out / "model.pkl")
    shutil.copy2(vdir / "features.json", out / "features.json")
    if (vdir / "code").is_dir():
        shutil.copytree(vdir / "code", out / "code")
    reqs = lock.read_text().rstrip("\n").splitlines()
    if not full_lock:
        local = {p.stem for p in (out / "code").glob("*.py")} if (out / "code").is_dir() else set()
        try:
            mods = pickle_modules(pkl)
        except Exception as e:  # noqa: BLE001 - a truncated/corrupt/exotic pickle: say so instead of a traceback
            raise RegistryError(f"cannot read the model pickle to decide what to install ({type(e).__name__}); "
                                "use full_lock=True (--full-lock)") from e
        reqs = lean_requirements(reqs, mods, local)
    for extra in ("fastapi", "uvicorn"):
        if not any(re.split(r"[=<>~! \[]", r.strip(), maxsplit=1)[0].lower() == extra for r in reqs):
            reqs.append(extra)
    (out / "requirements.txt").write_text("\n".join(reqs) + "\n")
    (out / "Dockerfile").write_text(DOCKERFILE)
    (out / "app.py").write_text(APP)
    _make_writable(out)  # registry copies are read-only; a rebuild must be able to clear this dir
    return out


def deploy_command(service: str, project: str, region: str, bundle: Path, *, model: str, version: str,
                   memory: str = "1Gi", cpu: str = "1", min_instances: int = 0, max_instances: int = 2,
                   concurrency: int = 8, allow_unauthenticated: bool = False) -> list[str]:
    if not SERVICE_RE.match(service):
        raise RegistryError(f"invalid Cloud Run service name {service!r}")
    if min_instances != 0:
        raise RegistryError("min_instances must be 0 (scale to zero); always-on instances bill continuously")
    if not 1 <= max_instances <= MAX_INSTANCES_CAP:
        raise RegistryError(f"max_instances must be 1..{MAX_INSTANCES_CAP}")
    label = lambda v: re.sub(r"[^a-z0-9_-]", "-", v.lower())[:60]
    return ["gcloud", "run", "deploy", service, "--source", str(bundle), "--project", project, "--region", region,
            "--memory", memory, "--cpu", cpu, "--min-instances", "0", "--max-instances", str(max_instances),
            "--concurrency", str(concurrency),
            "--allow-unauthenticated" if allow_unauthenticated else "--no-allow-unauthenticated",
            "--labels", f"mllab-model={label(model)},mllab-version={label(version)}", "--quiet"]


def rollback_command(service: str, project: str, region: str, revision: str) -> list[str]:
    if not re.match(r"^[a-z0-9-]+$", revision):
        raise RegistryError(f"invalid revision {revision!r}")
    return ["gcloud", "run", "services", "update-traffic", service, "--project", project, "--region", region,
            "--to-revisions", f"{revision}=100", "--quiet"]


def deploy(reg: Registry, project: str, model: str, version: str, *, service: str, region: str = "us-central1",
           work_dir: str | Path, confirm: str | None, dry_run: bool = True, runner=subprocess.run,
           account: str = "you@example.com", audit_path: Path | None = None, full_lock: bool = False, **opts) -> dict:
    if is_blocked_account(account):
        raise RegistryError("refusing work account")
    bundle = render_bundle(reg, project, model, version, work_dir, full_lock=full_lock)
    cmd = deploy_command(service, project, region, bundle, model=model, version=version, **opts)
    if dry_run:
        return {"changed": False, "dry_run": True, "bundle": str(bundle), "command": shlex.join(cmd)}
    require(f"deploy {service}", confirm)
    import os
    runner(cmd, check=True, env={**os.environ, "CLOUDSDK_CORE_ACCOUNT": account})
    reg.record_deploy(project, model, {"target": "cloudrun", "service": service, "version": version, "region": region})
    audit.record("cloudrun_deploy", path=audit_path, project=project, model=model, version=version,
                 service=service, region=region)
    return {"changed": True, "command": shlex.join(cmd)}
